"""Convert shape-matched ANSI art (fg+bg truecolor) into C++ for the terminal intro.
usage: python3 gen_cpp.py src/introart.cpp PICTURE.ans[:ANIM.json] ...
  ANIM.json (optional) is the fire and smoke animation from gen_shape_anim.py.
Colours are reduced to the xterm-256 palette so plain macOS Terminal shows them too.
"""
import json, re, sys

out, sources = sys.argv[1], sys.argv[2:]
rx = re.compile(r'\x1b\[38;2;(\d+);(\d+);(\d+);48;2;(\d+);(\d+);(\d+)m(.)')
CUBE = [0, 95, 135, 175, 215, 255]

def to256(r, g, b):
    def near(v):
        return min(range(6), key=lambda i: abs(CUBE[i] - v))
    ci = (near(r), near(g), near(b))
    d_cube = sum((v - CUBE[i]) ** 2 for v, i in zip((r, g, b), ci))
    gi = max(0, min(23, round(((r + g + b) / 3 - 8) / 10)))
    gv = 8 + 10 * gi
    d_gray = sum((v - gv) ** 2 for v in (r, g, b))
    return 232 + gi if d_gray < d_cube else 16 + 36 * ci[0] + 6 * ci[1] + ci[2]

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

lines = ['// Generated by art/tools/gen_cpp.py from the game ad (art/). Do not edit by hand.',
         '#include "introart.hpp"', '', 'namespace IntroArt {', '']
variants = []
for n, arg in enumerate(sources):
    src, _, anim_path = arg.partition(':')
    grid = [rx.findall(l) for l in open(src).read().rstrip('\n').split('\n')]
    rows, cols = len(grid), len(grid[0])
    lines.append(f'static const char* const chars{n}[{rows}] = {{')
    lines += [f'    "{esc("".join(c[6] for c in row))}",' for row in grid]
    lines.append('};')
    for name, sl in (('fg', slice(0, 3)), ('bg', slice(3, 6))):
        lines.append(f'static const uint8_t {name}{n}[{rows}][{cols}] = {{')
        for row in grid:
            lines.append('    {' + ','.join(str(to256(*map(int, c[sl]))) for c in row) + '},')
        lines.append('};')
    anim = None
    if anim_path:
        A = json.load(open(anim_path))
        assert (A['cols'], A['rows']) == (cols, rows), 'animation does not match the picture'
        cells, frames = A['cells'], A['frames_data']
        lines.append(f'static const uint16_t animCells{n}[{len(cells)}] = {{')
        for i in range(0, len(cells), 24):
            lines.append('    ' + ','.join(map(str, cells[i:i + 24])) + ',')
        lines.append('};')
        lines.append(f'static const char* const animChars{n}[{len(frames)}] = {{')
        lines += [f'    "{esc("".join(c[0] for c in fr))}",' for fr in frames]
        lines.append('};')
        for name, k in (('animFg', 1), ('animBg', 2)):
            lines.append(f'static const uint8_t {name}{n}[{len(frames)}][{len(cells)}] = {{')
            for fr in frames:
                lines.append('    {' + ','.join(str(to256(*c[k])) for c in fr) + '},')
            lines.append('};')
        anim = (len(frames), len(cells))
    lines.append('')
    variants.append((cols, rows, n, anim))

lines.append('// largest first')
lines.append(f'const Picture PICTURES[{len(variants)}] = {{')
for cols, rows, n, anim in sorted(variants, key=lambda v: v[0], reverse=True):
    a = (f'{anim[0]}, {anim[1]}, animCells{n}, animChars{n}, &animFg{n}[0][0], &animBg{n}[0][0]'
         if anim else '0, 0, nullptr, nullptr, nullptr, nullptr')
    lines.append(f'    {{ {cols}, {rows}, chars{n}, &fg{n}[0][0], &bg{n}[0][0], {a} }},')
lines += ['};', f'const int PICTURE_COUNT = {len(variants)};', '', '} // namespace IntroArt', '']
open(out, 'w').write('\n'.join(lines))
print(out, [(c, r, a) for c, r, _, a in variants])
